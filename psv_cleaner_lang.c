const char *TR(UiTextId id) {
    int lang = currentLanguage;
    if (lang < 0 || lang >= MAX_LANGUAGES) lang = LANGUAGE_EN;
    if (id < 0 || id >= TXT_COUNT) return "";
    const char *s = UI_STRINGS[lang][id];
    if (!s || s[0] == '\0') return UI_STRINGS[LANGUAGE_EN][id];
    return s;
}

